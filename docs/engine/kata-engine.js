/* ─────────────── live console (only when a real console is attached) ─────────────── */
let kick = null;
const isTTY = Boolean(process.stdin.isTTY);
const pipedLines = [];
let pipedClosed = false;

(function pipeWatcher() {
  if (!isTTY && process.stdin && typeof process.stdin.on === 'function') {
    try {
      process.stdin.setEncoding('utf8');
      process.stdin.on('data', ch => {
        for (const raw of String(ch).split('\n')) {
          const line = raw.replace(/\r$/, '').trim();
          if (line) pipedLines.push(line.toLowerCase());
        }
      });
      process.stdin.on('end', () => { pipedClosed = true; });
      if (typeof process.stdin.unref === 'function') process.stdin.unref(); // never keep the process alive just for stdin
    } catch { /* no stdin at all */ }
  }
})();

function stdinOpen() { return isTTY || !pipedClosed; }

function handleCommand(line) {
  if (line === 'delete' || line === 'reset' || line === 'wipe') { wipeMyInfo(); return; }
  if (line === 'status') { showStatus(); return; }
  if (line === 'renew') {
    if (kick) { log(cCyan('⟳ Renewing right now...')); kick(); }
    else log(cDim('ℹ  The first renewal is already running — this was it.'));
    return;
  }
  if (line === 'exit' || line === 'quit' || line === 'stop') { console.log(cDim(`◈ Bye! — © ${OWNER}`)); process.exit(0); }
  if (line) console.log(cDim(`   unknown command: "${line}" — try:  renew · status · delete · exit`));
}

function watchConsole() {
  if (isTTY) {
    console.log(cDim(`   ⌨  live console — type:  renew · status · delete (wipe my info) · exit   — © ${OWNER}`));
    const rl = require('node:readline').createInterface({ input: process.stdin, terminal: false });
    rl.on('line', l => handleCommand(String(l || '').trim().toLowerCase()));
    rl.on('close', () => { pipedClosed = true; });
  } else {
    // non-TTY: poll the piped lines gently — no blocking, no prompt output
    setInterval(() => {
      while (pipedLines.length) handleCommand(pipedLines.shift());
    }, 400).unref();
  }
}

/* ─────────────── cycle ─────────────── */
async function runOnce(creds) {
  try { return await attemptOnce(creds); }
  catch (e) { log(cRed(`✗ Unexpected error: ${e && e.stack ? e.stack.split('\n')[0] : e}`)); return 1; }
}

function startCycle(creds) {
  const everyMs = RENEW_EVERY_HOURS * 36e5;
  let timer = null;
  let busy = false;
  const cycle = async () => {
    if (busy || wiped) return;
    busy = true;
    const c = await runOnce(creds);
    busy = false;
    if (wiped) return;
    const delay = (c === 0 ? everyMs : RETRY_EVERY_MIN * 6e4) + rnd(-300, 300) * 1000;
    timer = setTimeout(cycle, delay);
    if (timer.unref) timer.unref();
  };
  kick = () => {
    if (busy) { log(cDim('ℹ  a renewal is already running.')); return; }
    if (timer) { clearTimeout(timer); timer = null; }
    cycle();
  };
  timer = setTimeout(cycle, everyMs + rnd(-300, 300) * 1000);
  if (timer.unref) timer.unref();
}

