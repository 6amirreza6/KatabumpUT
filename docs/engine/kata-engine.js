async function main() {
  if (has('--help') || has('-h')) { printHelp(); process.exit(0); }
  banner();

  if (has('--delete') || has('--reset')) { wipeMyInfo(); }
  if (has('--status')) { showStatus(); process.exit(0); }
  if (has('--login')) { await browserLogin(); process.exit(0); }

  const creds = loadCreds();
  if (!creds) {
    log(cRed('✗ This build has no readable personal vault — rebuild index.js on the official site:'));
    log(cDim(`   ${SITE}`));
    process.exit(2);
  }
  log(cDim(`✦ Personal vault unsealed (AES-256-GCM) — account: ${creds.email}${creds.sids && creds.sids.length ? ' · server(s): ' + creds.sids.join(', ') : ''}`));

  if (!has('--once')) watchConsole();

  const code = await runOnce(creds);
  if (wiped) process.exit(0);
  if (has('--once')) process.exit(code || 0);

  if (code === 2 || code === 3 || code === 5) {
    log(cYellow(`⚠  Not through yet — I will keep retrying automatically every 15 minutes. (© ${OWNER})`));
  } else {
    log(cGreen(`🚀 Auto-renew is ON — a cycle every ${RENEW_EVERY_HOURS}h, retry every ${RETRY_EVERY_MIN}m after failures.`));
  }
  startCycle(creds);
}

process.on('SIGINT', () => { console.log(cDim(`\n◈ Bye! — © ${OWNER}`)); process.exit(0); });

if (require.main === module) {
  main().catch(e => { console.error(e); process.exit(1); });
}

